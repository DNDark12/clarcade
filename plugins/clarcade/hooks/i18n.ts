export function words(language) {
  return language === 'vi' ? vietnamese : english
}

export function languageOf(value, locale) {
  if (value === 'en' || value === 'vi') return value
  return /^vi(?:$|[-_.])/i.test(locale ?? '') ? 'vi' : 'en'
}

